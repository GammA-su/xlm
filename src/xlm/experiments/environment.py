"""Location-independent identity of the selected installed offline runtime.

Policy v1 hashes every regular site-packages file except generated bytecode,
installer bookkeeping/RECORD, and this project's editable installation. XLM comes
only from the separately verified capture. Executable .pth hooks are never run by
the worker. The interpreter executable is hashed; its stdlib and OS libraries are
trusted bootstrap components, explicitly outside installed-file coverage.
"""

from __future__ import annotations

import importlib.metadata
import os
import platform
import re
import stat
import sys
import sysconfig
import time
import tomllib
from collections.abc import Iterator
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

from xlm.artifacts.manifest import ensure_plain_path, identity_digest
from xlm.artifacts.store import compute_file_sha256


def _installed_files(site: Path) -> Iterator[tuple[Path, int]]:
    directories = [site]
    entries = 0
    while directories:
        directory = directories.pop()
        with os.scandir(directory) as children:
            for child in children:
                entries += 1
                if entries > 100_000:
                    raise ValueError("installed runtime exceeds entry bound")
                if child.name == "__pycache__":
                    continue
                info = child.stat(follow_symlinks=False)
                if (
                    child.is_symlink()
                    or getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT
                ):
                    raise ValueError("installed runtime contains a symlink/junction")
                if child.is_dir(follow_symlinks=False):
                    directories.append(Path(child.path))
                elif child.is_file(follow_symlinks=False):
                    yield Path(child.path), info.st_size


def installed_runtime(lock: Path, extras: list[str], site: Path | None = None) -> dict[str, Any]:
    """Hash actual installed bytes; no imports of installed packages or network."""
    started = time.monotonic()
    if sorted(extras) not in (["cpu"], ["cpu", "eval"], ["cuda"], ["cuda", "eval"]):
        raise ValueError("execution requires explicit mutually exclusive CPU/CUDA extras")
    site = site or Path(sysconfig.get_paths()["purelib"])
    ensure_plain_path(site)
    if not site.is_dir() or lock.stat().st_size > 8 * 1024**2:
        raise ValueError("offline runtime or bounded lockfile unavailable")
    graph = tomllib.loads(lock.read_text(encoding="utf-8"))
    allowed: dict[str, set[str]] = {}
    for package in graph["package"]:
        name = re.sub(r"[-_.]+", "-", package["name"]).lower()
        allowed.setdefault(name, set()).add(package["version"])
    versions: dict[str, str] = {}
    distributions: dict[str, importlib.metadata.Distribution] = {}
    for distribution in importlib.metadata.distributions(path=[str(site)]):
        name = re.sub(r"[-_.]+", "-", distribution.metadata["Name"]).lower()
        if name == "xlm":
            continue
        if name in versions or distribution.version not in allowed.get(name, set()):
            raise ValueError(f"installed dependency is duplicate or not locked: {name}")
        versions[name] = distribution.version
        distributions[name] = distribution
    required = {"torch", "pydantic", "filelock", "typer", "psutil", "safetensors"}
    if "eval" in extras:
        required.add("lm-eval")
    if not required.issubset(versions):
        raise ValueError(f"missing offline dependencies: {sorted(required - versions.keys())}")
    from packaging.requirements import Requirement

    project = tomllib.loads((lock.parent / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    requirements = list(project["dependencies"])
    for extra in extras:
        requirements.extend(project["optional-dependencies"][extra])
    pending_requirements = [(Requirement(item), {""}) for item in requirements]
    checked: set[tuple[str, tuple[str, ...]]] = set()
    while pending_requirements:
        requirement, parent_extras = pending_requirements.pop()
        if requirement.marker and not any(
            requirement.marker.evaluate({"extra": e}) for e in parent_extras
        ):
            continue
        name = re.sub(r"[-_.]+", "-", requirement.name).lower()
        if name not in versions or not requirement.specifier.contains(versions[name]):
            raise ValueError(f"missing/incompatible offline dependency: {requirement}")
        selected_extras = {"", *requirement.extras}
        key = (name, tuple(sorted(selected_extras)))
        if key in checked:
            continue
        checked.add(key)
        pending_requirements.extend(
            (Requirement(item), selected_extras) for item in distributions[name].requires or []
        )
        if len(checked) > 2000 or time.monotonic() - started > 90:
            raise ValueError("offline dependency resolution exceeds bound")
    if ("+cpu" in versions["torch"]) != ("cpu" in extras):
        raise ValueError("installed torch accelerator does not match selected extras")
    pinned_python = lock.parent / ".python-version"
    if (
        not pinned_python.is_file()
        or pinned_python.read_text().strip() != platform.python_version()
    ):
        raise ValueError("actual interpreter does not match frozen Python patch pin")
    files: dict[str, tuple[str, int]] = {}
    pending: list[tuple[Path, int]] = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        for path, file_size in _installed_files(site):
            pending.append((path, file_size))
            if len(pending) == 64:
                _hash_batch(pending, site, files, pool)
                pending.clear()
            if time.monotonic() - started > 90:
                raise ValueError("installed runtime inventory exceeds time bound")
        _hash_batch(pending, site, files, pool)
    size = sum(item[1] for item in files.values())
    hashes = {name: item[0] for name, item in files.items()}
    return {
        "policy": "installed-files-v1",
        "python": platform.python_version(),
        "interpreter_sha256": compute_file_sha256(Path(sys.executable), max_bytes=256 * 1024**2),
        "base_interpreter_sha256": compute_file_sha256(
            Path(getattr(sys, "_base_executable", sys.executable)), max_bytes=256 * 1024**2
        ),
        "implementation": platform.python_implementation(),
        "platform": sys.platform,
        "machine": platform.machine(),
        "processor": platform.processor(),
        "os_version": platform.version(),
        "extras": sorted(extras),
        "distributions": versions,
        "installed_files_hash": identity_digest(hashes),
        "installed_file_count": len(files),
        "installed_bytes": size,
    }


def _hash_batch(
    batch: list[tuple[Path, int]],
    site: Path,
    files: dict[str, tuple[str, int]],
    pool: ThreadPoolExecutor,
) -> None:
    selected: list[tuple[Path, int]] = []
    for path, file_size in batch:
        relative = path.relative_to(site)
        if (
            "__pycache__" in relative.parts
            or path.suffix == ".pyc"
            or relative.parts[0].startswith(
                ("xlm-", "__editable__.xlm", "_xlm", "_editable_impl_xlm")
            )
            or relative.parts[0] == "xlm"
            or (
                ".dist-info" in relative.parts[0]
                and path.name in {"RECORD", "INSTALLER", "REQUESTED", "direct_url.json"}
            )
        ):
            continue
        if file_size > 8 * 1024**3 or len(files) + len(selected) >= 45_000:
            raise ValueError("installed runtime inventory exceeds byte/file bound")
        selected.append((path, file_size))
    if (
        sum(entry[1] for entry in files.values()) + sum(entry[1] for entry in selected)
        > 8 * 1024**3
    ):
        raise ValueError("installed runtime inventory exceeds aggregate byte bound")

    def hash_one(entry: tuple[Path, int]) -> str:
        return compute_file_sha256(entry[0], max_bytes=entry[1])

    for (path, file_size), digest in zip(selected, pool.map(hash_one, selected), strict=True):
        files[path.relative_to(site).as_posix()] = (digest, file_size)


def runtime_locations() -> dict[str, str]:
    """Incidental observations, never part of normalized runtime identity."""
    return {"python": sys.executable, "site_packages": sysconfig.get_paths()["purelib"]}
